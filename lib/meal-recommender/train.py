def main_training_pipeline(use_production_logs: bool = False):
    """
    Main training pipeline that orchestrates the complete workflow.
    
    Steps:
    1. Load cleaned recipe data from data_prep.py
    2. Generate synthetic user profiles (if not using production logs only)
    3. Create training pairs with feature engineering
    4. (Optional) Load and convert production events to training pairs
    5. (Optional) Combine datasets with production data weighted higher
    6. Split into train/test sets
    7. Train LGBMRegressor model
    8. Evaluate model performance
    9. Save model and metadata
    
    Args:
        use_production_logs: If True, load production data and combine with Food.com dataset
    """
    print("="*80)
    print("LightGBM Meal Ranker Training Pipeline")
    if use_production_logs:
        print("Mode: INCREMENTAL RETRAINING (Food.com + Production Data)")
    else:
        print("Mode: INITIAL TRAINING (Food.com Only)")
    print("="*80)
    
    # Step 1: Load cleaned recipe data
    print("\n[Step 1/7] Loading cleaned recipe data...")
    recipes_path = './data/RAW_recipes_cleaned.csv'
    
    if not os.path.exists(recipes_path):
        print(f"ERROR: Cleaned recipes file not found at {recipes_path}")
        print("Please run data_prep.py first to prepare the dataset.")
        sys.exit(1)
    
    recipes_df = pd.read_csv(recipes_path)
    print(f"✓ Loaded {len(recipes_df)} recipes")
    
    # Step 2: Generate synthetic user profiles and training pairs
    print("\n[Step 2/7] Generating synthetic user profiles...")
    n_users = 1000  # Start with 1000 users for reasonable training time
    synthetic_users = simulate_user_profiles(n=n_users)
    print(f"✓ Generated {len(synthetic_users)} synthetic users")
    
    # Step 3: Create training pairs from Food.com data
    print("\n[Step 3/7] Creating training pairs from Food.com dataset...")
    contexts_per_user = 5  # 5 different contexts per user
    food_X, food_y = create_training_pairs(recipes_df, synthetic_users, contexts_per_user)
    
    # Step 4: Load production data if requested
    production_X = []
    production_y = []
    
    if use_production_logs:
        print("\n[Step 4/7] Loading production events...")
        
        # Load environment variables for Supabase credentials
        supabase_url = os.getenv('SUPABASE_URL') or os.getenv('NEXT_PUBLIC_SUPABASE_URL')
        supabase_key = os.getenv('SUPABASE_SERVICE_KEY') or os.getenv('NEXT_PUBLIC_SUPABASE_ANON_KEY')
        
        if not supabase_url or not supabase_key:
            print("ERROR: SUPABASE_URL and SUPABASE_SERVICE_KEY environment variables required")
            print("Please set these in your environment or .env file")
            sys.exit(1)
        
        # Load production events from Supabase
        events_df = load_production_events(supabase_url, supabase_key)
        
        if not events_df.empty:
            # Convert events to training pairs
            print("\n[Step 4b/7] Converting production events to training pairs...")
            production_X, production_y = convert_events_to_pairs(events_df, recipes_df)
        else:
            print("⚠️  No production events found, continuing with Food.com data only")
    else:
        print("\n[Step 4/7] Skipping production logs (not requested)")
    
    # Step 5: Combine datasets
    print("\n[Step 5/7] Preparing final training dataset...")
    
    if production_X and production_y:
        # Combine Food.com and production data with production weighted 2x
        X, y = combine_datasets(food_X, food_y, production_X, production_y, production_weight=2.0)
        use_timestamp = True  # Use timestamped filename for retrained models
    else:
        # Use Food.com data only
        X = np.array(food_X, dtype=np.float32)
        y = np.array(food_y, dtype=np.float32)
        use_timestamp = False  # Use standard filename for initial training
    
    print(f"\n✓ Final training data shape: X={X.shape}, y={y.shape}")
    
    # Step 6: Train/test split
    print("\n[Step 6/7] Splitting into train/test sets...")
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.1, random_state=42
    )
    print(f"✓ Train set: {len(X_train):,} samples")
    print(f"✓ Test set: {len(X_test):,} samples")
    
    # Step 7: Train LGBMRegressor
    print("\n[Step 7/7] Training LGBMRegressor...")
    print("Hyperparameters:")
    print("  n_estimators: 100")
    print("  learning_rate: 0.1")
    print("  max_depth: 5")
    print("  num_leaves: 31")
    
    model = lgb.LGBMRegressor(
        n_estimators=100,
        learning_rate=0.1,
        max_depth=5,
        num_leaves=31,
        random_state=42,
        verbose=-1  # Suppress training output
    )
    
    model.fit(X_train, y_train)
    print("✓ Model training complete")
    
    # Step 8: Evaluate model
    print("\n[Step 8/7] Evaluating model...")
    metrics = evaluate_model(model, X_test, y_test)
    
    # Assert NDCG@5 threshold
    if metrics['ndcg_5'] < 0.3:
        error_msg = f"Model quality check FAILED: NDCG@5 ({metrics['ndcg_5']:.4f}) is below threshold (0.3)"
        print(f"\n❌ {error_msg}")
        raise ValueError(error_msg)
    
    # Step 9: Save model and metadata
    print("\n[Step 9/7] Saving model and metadata...")
    feature_names = [
        'macro_delta_calories',
        'macro_delta_protein',
        'macro_delta_carbs',
        'macro_delta_fat',
        'cuisine_match',
        'meal_slot_match',
        'days_since_last_eaten'
    ]
    
    model_filename = save_model_and_metadata(
        model, 
        metrics, 
        feature_names,
        use_timestamp=use_timestamp
    )
    
    print("\n" + "="*80)
    print("Training Pipeline Complete!")
    print("="*80)
    print(f"\n📊 Final Metrics:")
    print(f"  NDCG@5: {metrics['ndcg_5']:.4f}")
    print(f"  Precision@5: {metrics['precision_5']:.4f}")
    print(f"  MAE: {metrics['mae']:.4f}")
    print(f"\n✓ Model ready for deployment: lib/meal-recommender/{model_filename}")


