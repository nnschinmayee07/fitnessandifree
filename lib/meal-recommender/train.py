def create_training_pairs(
    recipes_df: pd.DataFrame,
    synthetic_users: pd.DataFrame,
    contexts_per_user: int = 10
) -> Tuple[List[List[float]], List[float]]:
    """
    Create (user, meal) training pairs with engineered features and ratings as labels.
    
    For each synthetic user, creates multiple contexts (different remaining macros and
    meal slot requests), then pairs each context with all recipes to create training examples.
    
    Args:
        recipes_df: DataFrame with cleaned recipe data including nutritional info and ratings
        synthetic_users: DataFrame with simulated user profiles
        contexts_per_user: Number of different contexts to generate per user
        
    Returns:
        Tuple of (X, y):
        - X: List of feature vectors (each is a list of 7 floats)
        - y: List of rating labels (continuous values from recipe ratings)
    """
    print("\n" + "="*80)
    print("Creating Training Pairs")
    print("="*80)
    
    X = []  # Feature vectors
    y = []  # Labels (ratings)
    
    total_users = len(synthetic_users)
    total_recipes = len(recipes_df)
    
    print(f"Synthetic users: {total_users}")
    print(f"Recipes: {total_recipes}")
    print(f"Contexts per user: {contexts_per_user}")
    print(f"Expected pairs: ~{total_users * contexts_per_user * total_recipes:,}")
    
    # Process users in batches for progress reporting
    for user_idx, user_row in synthetic_users.iterrows():
        if user_idx % 1000 == 0 and user_idx > 0:
            print(f"  Processed {user_idx}/{total_users} users... ({len(X):,} pairs generated)")
        
        # Convert user row to dict
        user_profile = user_row.to_dict()
        
        # Compute user's TDEE and macro targets
        tdee = compute_tdee(user_profile)
        targets = compute_macro_targets(user_profile, tdee)
        
        # Generate multiple contexts for this user (different times of day, meal slots)
        for context_idx in range(contexts_per_user):
            # Simulate remaining macros for this context
            remaining = simulate_remaining_macros(targets)
            
            # Simulate cuisine preference
            cuisine_pref = simulate_cuisine_preference()
            
            # Simulate meal slot request
            requested_slot = simulate_meal_slot_request()
            
            # Simulate user history (for recency feature)
            # For training, we'll simulate some meals as previously eaten
            user_history = []
            if random.random() < 0.3:  # 30% chance of having history
                # Randomly select 1-5 recipes as "previously eaten"
                num_history_items = random.randint(1, 5)
                sampled_recipes = recipes_df.sample(n=min(num_history_items, len(recipes_df)))
                for _, hist_recipe in sampled_recipes.iterrows():
                    days_ago = random.randint(1, 60)  # 1-60 days ago
                    user_history.append({
                        'meal_id': str(hist_recipe['id']),
                        'days_ago': days_ago
                    })
            
            # Create user context dict for feature engineering
            user_context = {
                'cuisine_preference': cuisine_pref,
                'requested_slot': requested_slot
            }
            
            # Pair this context with all recipes
            for _, recipe_row in recipes_df.iterrows():
                # Convert recipe to dict format for feature engineering
                recipe_dict = {
                    'id': str(recipe_row['id']),
                    'calories': recipe_row['calories'],
                    'protein_g': recipe_row['protein_g'],
                    'carbs_g': recipe_row['carbs_g'],
                    'fat_g': recipe_row['total_fat_g'],  # Note: using total_fat_g from data_prep
                    'cuisine_type': recipe_row['cuisine_type'],
                    'meal_slot': recipe_row['meal_slot']
                }
                
                # Engineer features for this (user, meal) pair
                features = engineer_features(user_context, recipe_dict, remaining, user_history)
                
                # Use recipe rating as the label
                # Ratings in Food.com are typically 1-5 stars
                # We need to handle the 'rating' column from interactions data
                # For now, we'll use a synthetic rating based on fit quality
                # In a real scenario, we'd join with interactions data
                
                # Compute a synthetic rating based on feature quality
                # This is a placeholder - ideally we'd use actual user ratings from interactions
                rating = compute_synthetic_rating(features)
                
                X.append(features)
                y.append(rating)
    
    print(f"\n✓ Generated {len(X):,} training pairs")
    print(f"  Feature vector size: {len(X[0])} features")
    print(f"  Label distribution: min={min(y):.2f}, max={max(y):.2f}, mean={np.mean(y):.2f}")
    
    return X, y


def compute_synthetic_rating(features: List[float]) -> float:
    """
    Compute a synthetic rating based on feature quality.
    
    This is a placeholder for actual user ratings. In production, we'd use
    real ratings from the interactions dataset. For training purposes, we
    create synthetic ratings based on how well the meal "fits" the user context.
    
    Rating logic:
    - Start at 3.0 (neutral rating)
    - Penalize large macro deltas (poor nutritional fit)
    - Boost for cuisine match (+0.5)
    - Boost for meal slot match (+1.0, critical)
    - Slight boost for recency (variety)
    
    Args:
        features: 7-element feature vector
        
    Returns:
        Synthetic rating (1.0 to 5.0)
    """
    base_rating = 3.0
    
    # Extract features
    cal_delta = features[0]
    protein_delta = features[1]
    carbs_delta = features[2]
    fat_delta = features[3]
    cuisine_match = features[4]
    slot_match = features[5]
    days_since = features[6]
    
    # Penalize large macro deltas (poor fit)
    # Normalize deltas to 0-1 range and penalize
    cal_penalty = min(cal_delta / 500, 1.0) * -1.5  # Up to -1.5 stars
    protein_penalty = min(protein_delta / 50, 1.0) * -0.5  # Up to -0.5 stars
    carbs_penalty = min(carbs_delta / 50, 1.0) * -0.3  # Up to -0.3 stars
    fat_penalty = min(fat_delta / 30, 1.0) * -0.3  # Up to -0.3 stars
    
    # Boost for matches
    cuisine_boost = 0.5 if cuisine_match == 1 else 0
    slot_boost = 1.0 if slot_match == 1 else -1.0  # Critical feature
    
    # Slight boost for variety (newer meals)
    recency_boost = 0.2 if days_since > 14 else 0
    
    # Compute final rating
    rating = base_rating + cal_penalty + protein_penalty + carbs_penalty + fat_penalty
    rating += cuisine_boost + slot_boost + recency_boost
    
    # Clamp to 1.0-5.0 range
    rating = max(1.0, min(5.0, rating))
    
    # Add some noise to make it more realistic
    rating += np.random.normal(0, 0.2)
    rating = max(1.0, min(5.0, rating))
    
    return rating


def evaluate_model(
    model: lgb.LGBMRegressor,
    X_test: np.ndarray,
    y_test: np.ndarray
) -> Dict[str, float]:
    """
    Evaluate the trained model on test set.
    
    Computes three key metrics:
    1. NDCG@5: Normalized Discounted Cumulative Gain at rank 5
       - Measures ranking quality for top-5 recommendations
       - Range: 0.0 (worst) to 1.0 (perfect)
       - Target: >= 0.3
    
    2. Precision@5: Fraction of top-5 that are high-quality (rating >= 4.0)
       - Measures what % of recommendations are actually good
       - Range: 0.0 to 1.0
       - Target: >= 0.6
    
    3. MAE: Mean Absolute Error for rating prediction
       - Measures prediction accuracy
       - Lower is better
    
    Args:
        model: Trained LGBMRegressor
        X_test: Test feature vectors
        y_test: Test labels (ratings)
        
    Returns:
        Dictionary with metrics: ndcg_5, precision_5, mae
    """
    print("\n" + "="*80)
    print("Evaluating Model on Test Set")
    print("="*80)
    
    # Predict scores on test set
    y_pred = model.predict(X_test)
    
    # Compute MAE
    mae = mean_absolute_error(y_test, y_pred)
    print(f"\nMean Absolute Error: {mae:.4f}")
    
    # Compute NDCG@5
    # NDCG requires multiple queries (user contexts), so we'll compute it in groups
    # We'll treat each 100 consecutive samples as one "query" for simplicity
    group_size = 100
    n_groups = len(y_test) // group_size
    
    ndcg_scores = []
    precision_scores = []
    
    for i in range(n_groups):
        start_idx = i * group_size
        end_idx = start_idx + group_size
        
        y_true_group = y_test[start_idx:end_idx]
        y_pred_group = y_pred[start_idx:end_idx]
        
        # Compute NDCG@5 for this group
        # Reshape for sklearn's ndcg_score (expects 2D array)
        try:
            ndcg = ndcg_score([y_true_group], [y_pred_group], k=5)
            ndcg_scores.append(ndcg)
        except:
            # Skip if NDCG computation fails for this group
            pass
        
        # Compute Precision@5 for this group
        # Get top-5 indices by predicted score
        top5_indices = np.argsort(y_pred_group)[-5:]
        top5_true_ratings = y_true_group[top5_indices]
        
        # Count how many are high-quality (rating >= 4.0)
        high_quality_count = np.sum(top5_true_ratings >= 4.0)
        precision = high_quality_count / 5.0
        precision_scores.append(precision)
    
    # Average across all groups
    avg_ndcg_5 = np.mean(ndcg_scores) if ndcg_scores else 0.0
    avg_precision_5 = np.mean(precision_scores)
    
    print(f"NDCG@5: {avg_ndcg_5:.4f}")
    print(f"Precision@5: {avg_precision_5:.4f}")
    
    # Check baseline threshold
    if avg_ndcg_5 < 0.3:
        print(f"\n⚠️  WARNING: NDCG@5 ({avg_ndcg_5:.4f}) is below baseline threshold (0.3)")
    else:
        print(f"\n✓ NDCG@5 meets baseline threshold (>= 0.3)")
    
    return {
        'ndcg_5': avg_ndcg_5,
        'precision_5': avg_precision_5,
        'mae': mae
    }


def save_model_and_metadata(
    model: lgb.LGBMRegressor,
    metrics: Dict[str, float],
    feature_names: List[str],
    output_dir: str = '.',
    use_timestamp: bool = False
):
    """
    Save trained model, feature schema, and training metrics to disk.
    
    Saves three files:
    1. meal_ranker.txt (or meal_ranker_{timestamp}.txt): Serialized LightGBM model
    2. feature_schema.json: Feature metadata for validation
    3. training_metrics.json: Performance baseline metrics
    
    Args:
        model: Trained LGBMRegressor
        metrics: Dictionary with evaluation metrics
        feature_names: List of feature names in order
        output_dir: Directory to save files (default: current directory)
        use_timestamp: If True, append timestamp to model filename
    """
    print("\n" + "="*80)
    print("Saving Model and Metadata")
    print("="*80)
    
    # Use absolute path
    output_dir = os.path.abspath(output_dir)
    
    # Create output directory if it doesn't exist
    os.makedirs(output_dir, exist_ok=True)
    
