def compute_tdee(profile: Dict[str, Any]) -> float:
    """
    Calculate Total Daily Energy Expenditure using Mifflin-St Jeor equation.
    
    TDEE = BMR × Activity Multiplier
    BMR (Basal Metabolic Rate) = 10 × weight(kg) + 6.25 × height(cm) - 5 × age(years) + s
    where s = +5 for males, -161 for females (we'll use average: -78)
    
    Activity Multipliers:
    - sedentary: 1.2
    - lightly_active: 1.375
    - moderately_active: 1.55
    - very_active: 1.725
    - extra_active: 1.9
    
    Args:
        profile: Dictionary with keys: age, weight_kg, height_cm, activity_level
        
    Returns:
        Total Daily Energy Expenditure in calories
    """
    # Mifflin-St Jeor BMR calculation (using averaged gender constant)
    bmr = (10 * profile['weight_kg'] + 
           6.25 * profile['height_cm'] - 
           5 * profile['age'] - 78)
    
    # Activity multipliers
    activity_multipliers = {
        'sedentary': 1.2,
        'lightly_active': 1.375,
        'moderately_active': 1.55,
        'very_active': 1.725,
        'extra_active': 1.9
    }
    
    multiplier = activity_multipliers.get(profile['activity_level'], 1.55)
    tdee = bmr * multiplier
    
    return round(tdee, 1)


def compute_macro_targets(profile: Dict[str, Any], tdee: float) -> Dict[str, float]:
    """
    Calculate daily protein, carbs, and fat targets based on TDEE and goal.
    
    Macro Distribution Strategy:
    - Weight Loss: High protein, moderate carbs, moderate fat (deficit: -500 cal)
      * Protein: 2.0g/kg bodyweight (higher to preserve muscle)
      * Fat: 25% of calories
      * Carbs: remainder
      
    - Maintenance: Balanced macros
      * Protein: 1.6g/kg bodyweight
      * Fat: 30% of calories
      * Carbs: remainder
      
    - Muscle Gain: High protein, high carbs, moderate fat (surplus: +300 cal)
      * Protein: 2.2g/kg bodyweight (higher for muscle synthesis)
      * Fat: 25% of calories
      * Carbs: remainder
    
    Calorie Adjustments:
    - Weight Loss: TDEE - 500
    - Maintenance: TDEE
    - Muscle Gain: TDEE + 300
    
    Args:
        profile: Dictionary with keys: weight_kg, goal
        tdee: Total Daily Energy Expenditure in calories
        
    Returns:
        Dictionary with keys: calories, protein_g, carbs_g, fat_g
    """
    weight_kg = profile['weight_kg']
    goal = profile['goal']
    
    # Adjust calories based on goal
    if goal == 'weight_loss':
        target_calories = tdee - 500
        protein_per_kg = 2.0
        fat_percentage = 0.25
    elif goal == 'muscle_gain':
        target_calories = tdee + 300
        protein_per_kg = 2.2
        fat_percentage = 0.25
    else:  # maintenance
        target_calories = tdee
        protein_per_kg = 1.6
        fat_percentage = 0.30
    
    # Calculate protein target (g/kg bodyweight)
    protein_g = weight_kg * protein_per_kg
    protein_calories = protein_g * 4  # 4 calories per gram of protein
    
    # Calculate fat target (percentage of total calories)
    fat_calories = target_calories * fat_percentage
    fat_g = fat_calories / 9  # 9 calories per gram of fat
    
    # Calculate carbs (remainder after protein and fat)
    carbs_calories = target_calories - protein_calories - fat_calories
    carbs_g = carbs_calories / 4  # 4 calories per gram of carbs
    
    return {
        'calories': round(target_calories, 1),
        'protein_g': round(protein_g, 1),
        'carbs_g': round(max(0, carbs_g), 1),  # Ensure non-negative
        'fat_g': round(fat_g, 1)
    }


def simulate_remaining_macros(targets: Dict[str, float]) -> Dict[str, float]:
    """
    Simulate remaining macros by generating random consumption (0-100% of targets).
    
    This simulates a user at various points throughout their day:
    - Early morning: 90-100% remaining (little consumed)
    - Mid-day: 40-70% remaining (some meals logged)
    - Evening: 10-40% remaining (most meals logged)
    
    We use a beta distribution to create realistic consumption patterns.
    
    Args:
        targets: Dictionary with keys: calories, protein_g, carbs_g, fat_g
        
    Returns:
        Dictionary with remaining amounts for: calories, protein_g, carbs_g, fat_g
    """
    # Beta distribution creates realistic consumption patterns
    # alpha=2, beta=2 gives a bell curve centered at 50%
    # alpha=2, beta=5 skews towards lower consumption (early day)
    # alpha=5, beta=2 skews towards higher consumption (late day)
    
    # Mix of time-of-day scenarios
    scenario = random.choice(['early', 'mid', 'late'])
    
    if scenario == 'early':
        # Early day: 80-100% remaining
        consumption_pct = np.random.beta(2, 8)  # Skewed towards low consumption
    elif scenario == 'mid':
        # Mid-day: 30-70% remaining
        consumption_pct = np.random.beta(5, 5)  # Centered around 50%
    else:  # late
        # Late day: 0-30% remaining
        consumption_pct = np.random.beta(8, 2)  # Skewed towards high consumption
    
    # Calculate remaining for each macro (add some variation per macro)
    remaining = {}
    for key in ['calories', 'protein_g', 'carbs_g', 'fat_g']:
        # Add ±10% variation per macro to simulate realistic uneven consumption
        macro_variation = np.random.uniform(0.9, 1.1)
        remaining_pct = 1 - (consumption_pct * macro_variation)
        remaining_pct = np.clip(remaining_pct, 0, 1)  # Ensure 0-100%
        
        remaining[key] = round(targets[key] * remaining_pct, 1)
    
    return remaining


